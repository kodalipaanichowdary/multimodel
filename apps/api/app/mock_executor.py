"""P1 ONLY: scripted fake execution. Replaced by the real runtime in P2.

Emits a fixed, contract-valid event sequence so the UI can be built against
real wire traffic. A prompt containing the word "fail" takes the failure path.
Agents passed as `extra` (POST /tasks `selected`) each get one scripted step.
"""

from __future__ import annotations

import asyncio
import re
import time
from collections.abc import Iterator, Sequence
from dataclasses import dataclass
from typing import Any
from uuid import uuid4

from pos_schemas import make_event

from .bus import EventBus

Step = tuple[str, dict[str, Any]]

BASE_PLAN = (
    ("research", "Gather sources"),
    ("writer", "Draft artifact"),
    ("validator", "Check output"),
)
BUILTIN = frozenset({"orchestrator", *(a for a, _ in BASE_PLAN)})


@dataclass(frozen=True)
class ExtraAgent:
    id: str
    name: str


def _report(prompt: str, plan: Sequence[tuple[str, str]]) -> str:
    steps = "\n".join(f"{i}. **{a}** — {g}" for i, (a, g) in enumerate(plan, 1))
    return (
        "# Report (mock)\n\n"
        f"**Task:** {prompt}\n\n"
        "## Plan\n"
        f"{steps}\n\n"
        "## Findings\n"
        "- Source A — overview (mock)\n"
        "- Source B — details (mock)\n"
        "- Source C — counterpoint (mock)\n\n"
        "> Generated by the P1 mock executor. No model was called.\n"
    )


def script(prompt: str, task_id: str, extra: Sequence[ExtraAgent] = ()) -> Iterator[Step]:
    fail = re.search(r"\bfail\b", prompt, re.IGNORECASE) is not None
    c1, c2, appr, art = (f"{p}-{task_id[:8]}" for p in ("call1", "call2", "appr", "art"))
    extras = [a for a in dict.fromkeys(extra) if a.id not in BUILTIN]
    # selected agents run after the writer, before validation
    plan = [*BASE_PLAN[:2], *((a.id, f"{a.name}: assigned step") for a in extras), BASE_PLAN[2]]

    yield "task.created", {"prompt": prompt}
    yield "agent.started", {"agent_id": "orchestrator", "parent_id": None}
    yield "agent.thinking", {"agent_id": "orchestrator", "message": "Decomposing task"}
    yield "task.planned", {"steps": [{"agent_id": a, "goal": g} for a, g in plan]}
    yield "agent.started", {"agent_id": "research", "parent_id": "orchestrator"}
    yield "agent.thinking", {"agent_id": "research", "message": "Choosing queries"}
    yield (
        "tool.started",
        {
            "agent_id": "research",
            "tool_id": "web_search",
            "call_id": c1,
            "args": {"q": prompt[:80], "k": 3},
        },
    )
    if fail:
        yield (
            "tool.failed",
            {
                "agent_id": "research",
                "tool_id": "web_search",
                "call_id": c1,
                "error": "mock: upstream timeout",
            },
        )
        yield "execution.failed", {"error": "research step failed", "agent_id": "research"}
        return
    yield (
        "tool.completed",
        {
            "agent_id": "research",
            "tool_id": "web_search",
            "call_id": c1,
            "duration_ms": 420,
            "result_preview": "3 results (mock)",
        },
    )
    yield "agent.completed", {"agent_id": "research", "summary": "3 sources found (mock)"}
    yield "agent.started", {"agent_id": "writer", "parent_id": "orchestrator"}
    yield "agent.thinking", {"agent_id": "writer", "message": "Outlining"}
    yield (
        "approval.requested",
        {
            "approval_id": appr,
            "agent_id": "writer",
            "tool_id": "fs_write",
            "reason": "write report.md",
        },
    )
    yield "approval.granted", {"approval_id": appr, "by": "mock-auto"}
    yield (
        "tool.started",
        {"agent_id": "writer", "tool_id": "fs_write", "call_id": c2, "args": {"path": "report.md"}},
    )
    yield (
        "tool.completed",
        {
            "agent_id": "writer",
            "tool_id": "fs_write",
            "call_id": c2,
            "duration_ms": 35,
            "result_preview": "wrote 1.2 KB (mock)",
        },
    )
    yield "agent.completed", {"agent_id": "writer", "summary": "Draft ready (mock)"}
    for a in extras:
        yield "agent.started", {"agent_id": a.id, "parent_id": "orchestrator"}
        yield "agent.thinking", {"agent_id": a.id, "message": "Working on assigned step"}
        yield "agent.completed", {"agent_id": a.id, "summary": f"{a.name} step done (mock)"}
    yield "agent.started", {"agent_id": "validator", "parent_id": "orchestrator"}
    yield "agent.thinking", {"agent_id": "validator", "message": "Checking schema"}
    yield "agent.completed", {"agent_id": "validator", "summary": "valid (mock)"}
    yield (
        "artifact.created",
        {
            "artifact_id": art,
            "agent_id": "writer",
            "title": "Report",
            "mime": "text/markdown",
            "content": _report(prompt, plan),
        },
    )
    yield "agent.completed", {"agent_id": "orchestrator", "summary": "Done (mock)"}
    yield "execution.completed", {"duration_ms": 0, "artifact_ids": [art]}


class MockExecutor:
    def __init__(self, bus: EventBus, step_delay_s: float) -> None:
        self._bus = bus
        self._delay = step_delay_s
        self._running: set[asyncio.Task[None]] = set()

    def submit(self, prompt: str, extra: Sequence[ExtraAgent] = ()) -> str:
        task_id = str(uuid4())
        t = asyncio.create_task(self._run(task_id, prompt, tuple(extra)), name=f"mock-{task_id}")
        self._running.add(t)
        t.add_done_callback(self._running.discard)
        return task_id

    async def _run(self, task_id: str, prompt: str, extra: tuple[ExtraAgent, ...]) -> None:
        started = time.monotonic()
        for seq, (etype, payload) in enumerate(script(prompt, task_id, extra)):
            if etype == "execution.completed":
                payload["duration_ms"] = int((time.monotonic() - started) * 1000)
            self._bus.publish(make_event(etype, task_id=task_id, seq=seq, payload=payload))
            await asyncio.sleep(self._delay)
